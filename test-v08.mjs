import assert from 'node:assert/strict';
import {COMBO,beginAttack,beginDodge,regenerateStamina,attackHit,enemyBehavior,shouldStrike} from './combat.js';
const p={x:100,y:350,w:32,h:68,face:1,stamina:100,attack:0,dodge:0,inv:0,combo:0,comboWindow:0,attackId:0};
const e={x:165,y:365,w:30,h:54,alive:true};
assert.equal(COMBO.length,3);
assert.equal(attackHit(p,e,0),true);
assert.equal(attackHit({...p,face:-1},e,0),false);
assert.equal(attackHit(p,{...e,x:300},0),false);
let a=beginAttack(p);assert.equal(a.index,0);assert.equal(p.stamina,82);
assert.equal(beginAttack(p),null,'must respect recovery');p.attack=0;
a=beginAttack(p);assert.equal(a.index,1);assert.equal(p.stamina,61);
p.attack=0;a=beginAttack(p);assert.equal(a.index,2);assert.equal(p.stamina,32);
p.attack=0;assert.equal(beginDodge(p),true);assert.equal(p.stamina,4);assert.ok(p.inv>0);
assert.equal(beginDodge(p),false);p.dodge=0;p.attack=0;p.comboWindow=0;
assert.equal(beginAttack(p),null,'insufficient stamina');regenerateStamina(p,1);assert.ok(p.stamina>30);
assert.equal(beginAttack(p).index,0,'new chain resets after timeout');
assert.equal(enemyBehavior('mourner').projectile,true);
assert.ok(enemyBehavior('mourner').range>enemyBehavior('gravebound').range);
assert.equal(shouldStrike(e,p,80),true);
console.log('OK: combo, timings, stamina, dodge, hit geometry, mourner ranged behavior.');
