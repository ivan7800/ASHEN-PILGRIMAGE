import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {BESTIARY,BESTIARY_BY_KIND,BESTIARY_AT_INDEX,BESTIARY_ART,bestiaryDamage,bestiaryFrame,bestiaryProjectileSpeed,bestiaryBurst,bestiaryRetreat,bestiaryStaminaDrain} from './bestiary-v37.js';
import {enemyBehavior,shouldStrike} from './combat.js';
import {createSaveManager,validateSave} from './save-manager.js';
import {FIRST_WITNESS_INDEX} from './final-throne-v30.js';
assert.equal(BESTIARY.length,23);
assert.equal(Object.keys(BESTIARY_AT_INDEX).length,23);
assert.equal(new Set(BESTIARY.map(e=>e.kind)).size,23);
assert.equal(new Set(BESTIARY.map(e=>e.index)).size,23);
assert.equal(FIRST_WITNESS_INDEX,72);
const bossIds=new Set([8,16,21,31,43,52,63,72]);
assert.ok(BESTIARY.every(e=>!bossIds.has(e.index)),'no alterar índices de jefes');
const projectile=[],shields=[],bursts=[];
for(const e of BESTIARY){
 assert.ok(e.index>=0&&e.index<73);
 assert.ok(e.visualWidth>=110&&e.visualHeight>=100);
 assert.ok(e.hitWidth>=30&&e.hitHeight>=39);
 const b=enemyBehavior(e.kind);
 assert.equal(b.projectile,Boolean(e.config.projectile));
 assert.ok(b.aggro>=220&&b.damage>=10&&b.damage<=31);
 assert.ok(b.windup>=.52,'aviso de ataque mínimo');
 assert.ok(b.reach>b.range-2||b.projectile);
 const path=BESTIARY_ART[e.kind].replace('./','');
 assert.ok(existsSync(path),`${e.kind} sin atlas`);
 const png=readFileSync(path);
 assert.equal(png.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
 assert.equal(png.readUInt32BE(16),20*128);
 assert.equal(png.readUInt32BE(20),160);
 assert.equal(BESTIARY_BY_KIND[e.kind],e);
 if(b.projectile){projectile.push(e.kind);assert.ok(bestiaryProjectileSpeed(e.kind)>=140)}
 if(e.config.shield)shields.push(e.kind);
 if(bestiaryBurst(e.kind))bursts.push(e.kind);
}
assert.ok(projectile.length>=8,'caster y hostigadores no deben ser todos iguales');
assert.ok(shields.length>=2);
assert.ok(bursts.length>=2);
assert.ok(bestiaryRetreat('dreamweaver')>100);
assert.ok(bestiaryStaminaDrain('namecorrupter')>=15);
assert.equal(bestiaryDamage(30,{kind:'vesperaguard',dir:-1,x:100,w:39},{x:30,w:30}),16,'escudo bloquea de frente');
assert.equal(bestiaryDamage(30,{kind:'vesperaguard',dir:-1,x:100,w:39},{x:155,w:30}),30,'la espalda es vulnerable');
assert.equal(bestiaryDamage(30,{kind:'saltgolem',dir:-1,x:100,w:54},{x:30,w:30}),22);
assert.equal(bestiaryDamage(30,{kind:'gravebound',dir:-1,x:100,w:30},{x:30,w:30}),30,'combate histórico sin cambios');
const fake={kind:'sunfanatic',windup:1,strike:0,stagger:0,x:10};assert.ok([8,9].includes(bestiaryFrame(fake,480)));fake.windup=0;fake.strike=.1;assert.ok([10,11].includes(bestiaryFrame(fake,480)));
assert.equal(shouldStrike({x:100,y:300,w:39,h:62,dir:1},{x:45,y:300,w:32,h:68},105),false,'sin golpes al personaje por la espalda');
const saved={p:{x:530,hp:81,flasks:2,checkpoint:90},enemies:Array.from({length:73},(_,i)=>({hp:i===72?960:i===8?180:i===16?320:i===21?420:i===31?480:i===43?560:i===52?650:i===63?780:1,alive:true})),secrets:[{taken:false},{taken:false}],phase:'playing',kills:0};
assert.ok(validateSave(saved),'v3.6 sigue siendo un guardado válido');
const map=new Map(),storage={getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v),removeItem:k=>map.delete(k)};
const manager=createSaveManager(storage);manager.write('auto',saved);assert.deepEqual(manager.read('auto').enemies,saved.enemies);
console.log(`OK v3.7: ${BESTIARY.length} especies con atlas 20 fotogramas, ${projectile.length} a distancia, ${shields.length} escudos y ${bursts.length} embestidores. Guardados de 73 posiciones intactos.`);
